export const HERB_NAMES: Record<Exclude<SupportedLanguage, "en">, Record<string, string>> = { de: NAMES_DE, nl: NAMES_NL };
export const HERB_TEXT: Record<Exclude<SupportedLanguage, "en">, Record<string, string>> = { de: TEXT_DE, nl: TEXT_NL };

/** The herb or supplement name shown to the visitor. English keeps the id with spaces (shown with CSS capitalize). */
export function getHerbName(id: string, language: SupportedLanguage): string {
  if (language !== "en") {
    const translated = HERB_NAMES[language][id];
    if (translated) return translated;
  }
  return id.replace(/_/g, " ");
}

/** A benefit label, note, dosage or evidence sentence in the visitor's language; English is returned as is. */
export function translateHerbText(text: string, language: SupportedLanguage): string {
  if (language === "en" || !text) return text;
  return HERB_TEXT[language][text] ?? text;
}
